export type TranslationKey = keyof typeof TRANSLATIONS.en;

export function translate(locale: LocaleCode, key: TranslationKey): string {
  return TRANSLATIONS[locale]?.[key] || TRANSLATIONS.en[key];
}

export function getTransactionTypeLabel(locale: LocaleCode, type: TransactionType): string {
  const key = `txType_${type}` as TranslationKey;
  return translate(locale, key);
}

export function formatLocaleDate(isoDate: string, locale: LocaleCode): string {
  if (!isoDate || !/^\d{4}-\d{2}-\d{2}$/.test(isoDate)) return isoDate;
  const [y, m, d] = isoDate.split('-').map(Number);
  const dt = new Date(Date.UTC(y, m - 1, d));
  return new Intl.DateTimeFormat(locale === 'fr' ? 'fr-FR' : 'en-US', {
    year: 'numeric',
    month: 'short',
    day: 'numeric',
    timeZone: 'UTC',
  }).format(dt);
}
