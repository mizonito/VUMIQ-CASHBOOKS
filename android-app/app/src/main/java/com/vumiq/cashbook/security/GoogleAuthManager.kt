package com.vumiq.cashbook.security

import android.content.Context
import androidx.credentials.ClearCredentialStateRequest
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import androidx.credentials.exceptions.GetCredentialCancellationException
import androidx.credentials.exceptions.NoCredentialException
import com.google.android.libraries.identity.googleid.GetGoogleIdOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.firebase.FirebaseApp
import com.google.firebase.auth.FirebaseAuth
import com.google.firebase.auth.GoogleAuthProvider
import com.vumiq.cashbook.BuildConfig
import kotlinx.coroutines.tasks.await

data class CloudAccountSnapshot(
    val isFirebaseConfigured: Boolean = false,
    val isSignedIn: Boolean = false,
    val uid: String = "",
    val email: String = "",
    val displayName: String = "",
    val isEmailVerified: Boolean = false,
    val authError: String? = null
)

sealed interface GoogleSignInResult {
    data class Success(val snapshot: CloudAccountSnapshot) : GoogleSignInResult
    data object Cancelled : GoogleSignInResult
    data class Error(val message: String) : GoogleSignInResult
}

/**
 * Native Android Google Sign-In manager built on Jetpack Credential Manager
 * (`androidx.credentials` + Google Identity Services `googleid`) and Firebase Auth.
 *
 * Gracefully degrades when `google-services.json` is not bundled, keeping offline
 * Room SQLite cashbook operations 100% functional without external credentials.
 */
class GoogleAuthManager(private val appContext: Context) {

    fun isFirebaseConfigured(): Boolean =
        runCatching { FirebaseApp.getApps(appContext).isNotEmpty() }.getOrDefault(false)

    /**
     * Resolves the OAuth 2.0 Web Client ID (`serverClientId`) required by Credential Manager:
     * 1. Prefers `R.string.default_web_client_id` generated by the `google-services` Gradle plugin
     *    from `google-services.json` when present.
     * 2. Falls back to `BuildConfig.GOOGLE_WEB_CLIENT_ID` configured for the VUMIQ workspace.
     */
    fun resolveServerClientId(): String {
        val resId = appContext.resources.getIdentifier(
            "default_web_client_id",
            "string",
            appContext.packageName
        )
        if (resId != 0) {
            val fromRes = runCatching { appContext.getString(resId).trim() }.getOrDefault("")
            if (fromRes.isNotEmpty()) return fromRes
        }
        return BuildConfig.GOOGLE_WEB_CLIENT_ID.trim()
    }

    fun currentAccountSnapshot(authError: String? = null): CloudAccountSnapshot {
        if (!isFirebaseConfigured()) {
            return CloudAccountSnapshot(
                isFirebaseConfigured = false,
                authError = authError
            )
        }
        val user = runCatching { FirebaseAuth.getInstance().currentUser }.getOrNull()
            ?: return CloudAccountSnapshot(
                isFirebaseConfigured = true,
                isSignedIn = false,
                authError = authError
            )
        return CloudAccountSnapshot(
            isFirebaseConfigured = true,
            isSignedIn = true,
            uid = user.uid,
            email = user.email.orEmpty(),
            displayName = user.displayName.orEmpty(),
            isEmailVerified = user.isEmailVerified,
            authError = authError
        )
    }

    /**
     * Launches the native Android Credential Manager bottom sheet to authenticate with Google
     * and exchanges the Google ID token for a Firebase Authentication session.
     *
     * Note: [activityContext] must be an Activity context so Credential Manager can anchor its UI.
     */
    suspend fun signInWithGoogle(activityContext: Context): GoogleSignInResult {
        if (!isFirebaseConfigured()) {
            return GoogleSignInResult.Error(
                "Firebase is not configured in this build. Add google-services.json for com.vumiq.cashbook (or set VUMIQ_GOOGLE_SERVICES_JSON in GitHub Secrets) to enable Google Sign-In. Offline ledger remains fully active."
            )
        }

        val serverClientId = resolveServerClientId()
        if (serverClientId.isEmpty()) {
            return GoogleSignInResult.Error(
                "Missing OAuth 2.0 Web Client ID. Enable Google Sign-In in Firebase Console and update google-services.json."
            )
        }

        return try {
            val credentialManager = CredentialManager.create(activityContext)
            val googleIdOption = GetGoogleIdOption.Builder()
                .setFilterByAuthorizedAccounts(false)
                .setServerClientId(serverClientId)
                .setAutoSelectEnabled(false)
                .build()

            val request = GetCredentialRequest.Builder()
                .addCredentialOption(googleIdOption)
                .build()

            val response = credentialManager.getCredential(
                context = activityContext,
                request = request
            )

            val credential = response.credential
            if (credential !is CustomCredential ||
                credential.type != GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL
            ) {
                return GoogleSignInResult.Error("Unexpected credential type returned by Android Credential Manager.")
            }

            val googleIdTokenCredential = GoogleIdTokenCredential.createFrom(credential.data)
            val firebaseCredential = GoogleAuthProvider.getCredential(googleIdTokenCredential.idToken, null)
            val authResult = FirebaseAuth.getInstance().signInWithCredential(firebaseCredential).await()
            val user = authResult.user
                ?: return GoogleSignInResult.Error("Firebase Authentication completed without a user profile.")

            if (!user.isEmailVerified) {
                return GoogleSignInResult.Error(
                    "Signed in as ${user.email ?: user.uid}, but email_verified is false. VUMIQ Cloud Firestore security rules require a verified Google email."
                )
            }

            GoogleSignInResult.Success(currentAccountSnapshot(authError = null))
        } catch (_: GetCredentialCancellationException) {
            GoogleSignInResult.Cancelled
        } catch (_: NoCredentialException) {
            GoogleSignInResult.Error(
                "No Google account is signed in on this Android phone, or the release SHA-1 fingerprint is not registered in Firebase Console yet."
            )
        } catch (e: Exception) {
            GoogleSignInResult.Error(
                "Google Sign-In failed: ${e.localizedMessage ?: "Check network connection and Firebase SHA-1/SHA-256 registration."}"
            )
        }
    }

    /**
     * Signs out of Firebase Auth and clears Credential Manager auto-select state.
     * Never deletes or modifies any local Room financial records.
     */
    suspend fun signOut() {
        runCatching {
            if (isFirebaseConfigured()) {
                FirebaseAuth.getInstance().signOut()
            }
        }
        runCatching {
            CredentialManager.create(appContext).clearCredentialState(ClearCredentialStateRequest())
        }
    }
}
